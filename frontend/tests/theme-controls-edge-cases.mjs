import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
const output = new URL('../../outputs/theme-controls/', import.meta.url)
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await context.newPage()
const checks = [], errors = []
page.on('pageerror', error => errors.push(error.message))
const select = name => page.locator('.pms-form-control').filter({ has: page.getByRole('combobox', { name, exact: true }) })
const shot = name => page.screenshot({ path: new URL(name + '.png', output).pathname, animations: 'disabled' })
try {
  await page.goto('http://127.0.0.1:5184/')
  await page.getByRole('button', { name: '切换外观' }).click()
  await page.getByRole('menuitem', { name: '青绿' }).click()
  await page.goto('http://127.0.0.1:5184/')
  await expect(page.locator('html')).toHaveAttribute('data-preview-theme', 'teal')
  const sibling = await context.newPage()
  await sibling.goto('http://127.0.0.1:5184/')
  await sibling.getByRole('button', { name: '切换外观' }).click()
  await sibling.getByRole('menuitem', { name: '石墨' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-preview-theme', 'graphite')
  await sibling.close()
  checks.push('theme preference survives fresh entry and synchronizes open preview tabs')

  await page.getByRole('button', { name: '表单与状态', exact: true }).click()
  await select('部门树多选').click()
  const tree = page.getByRole('tree')
  await tree.getByRole('treeitem', { name: '研发项目部', exact: true }).locator('label').click()
  await expect(select('部门树多选')).toContainText('+ 2')
  await page.keyboard.press('Escape')
  await select('空选项').click()
  await expect(page.getByText('暂无可选记录', { exact: true })).toBeVisible()
  await shot('empty-options')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '模拟加载', exact: true }).click()
  await expect(page.getByRole('button', { name: '模拟加载', exact: true })).toHaveClass(/is-loading/)
  await expect(page.getByRole('button', { name: '模拟加载', exact: true })).not.toHaveClass(/is-loading/)
  await page.locator('.inline-value').click()
  await page.getByRole('textbox', { name: '行内备注', exact: true }).fill('行内修改测试')
  await page.keyboard.press('Enter')
  await expect(page.locator('.inline-value')).toContainText('行内修改测试')
  const checkbox = page.getByRole('checkbox', { name: '启用勾选', exact: true })
  const checkboxShell = page.locator('.pms-form-control--binary').filter({ has: checkbox })
  await checkboxShell.locator('label').click()
  await expect(checkboxShell).toHaveCSS('outline-style', 'none')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Shift+Tab')
  await expect(checkbox).toBeFocused()
  await expect(checkboxShell).toHaveCSS('outline-style', 'solid')
  await page.getByRole('button', { name: '校验样稿', exact: true }).hover()
  await expect(page.getByRole('button', { name: '校验样稿', exact: true })).toHaveCSS('background-color', 'rgb(9, 9, 11)')
  await shot('keyboard-focus-and-hover')
  checks.push('tree selection, empty options, loading feedback, inline editing, mouse/keyboard focus and hover')

  await page.getByRole('button', { name: '表格编辑', exact: true }).click()
  const numberCell = page.locator('.ag-center-cols-container .ag-row[row-id="1"] [col-id="quantity"]')
  await numberCell.dblclick()
  await page.getByRole('spinbutton', { name: '编辑数量', exact: true }).fill('12.5')
  await page.keyboard.press('Enter')
  await expect(numberCell).toContainText('12.5')
  const dateCell = page.locator('.ag-center-cols-container .ag-row[row-id="1"] [col-id="date"]')
  await dateCell.dblclick()
  await page.getByRole('combobox', { name: '编辑登记日期', exact: true }).click()
  await expect(page.locator('.el-picker-panel:visible')).toBeVisible()
  await shot('grid-date-editor')
  await page.locator('.el-picker-panel:visible .el-date-table td.available:not(.prev-month):not(.next-month)').nth(6).click()
  await page.locator('.pms-header h1').click()
  await expect(dateCell).toContainText('2026-10-07')
  checks.push('AG Grid number and date editors commit correctly')

  for (const width of [768, 390]) {
    await page.setViewportSize({ width, height: 844 })
    await page.getByRole('button', { name: '表单与状态', exact: true }).click()
    await page.locator('.pms-form-control[aria-label="日期范围"]').click()
    const picker = page.locator('.el-date-range-picker:visible')
    await expect(picker).toBeVisible()
    await shot('range-' + width)
    const bounds = await picker.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width, `range popup overflows ${width}: ${JSON.stringify(bounds)}`)
    assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= 844, `range popup exceeds viewport height at ${width}: ${JSON.stringify(bounds)}`)
    if (width === 390) {
      const start = picker.locator('.is-left .el-date-table td.available:not(.prev-month):not(.next-month)').nth(4)
      const end = picker.locator('.is-right .el-date-table td.available:not(.prev-month):not(.next-month)').nth(6)
      await start.click()
      await end.click()
      await expect(page.locator('.pms-form-control[aria-label="日期范围"] input').first()).toHaveValue('2026-10-05')
      await expect(page.locator('.pms-form-control[aria-label="日期范围"] input').last()).toHaveValue('2026-11-07')
    }
    await page.keyboard.press('Escape')
    await select('产品线多选').click()
    const dropdown = page.locator('.el-select__popper:visible')
    await expect(dropdown).toBeVisible()
    await shot('multi-' + width)
    const selectBounds = await dropdown.boundingBox()
    assert.ok(selectBounds.x >= 0 && selectBounds.x + selectBounds.width <= width, `select popup overflows ${width}`)
    await page.keyboard.press('Escape')
  }
  checks.push('opened date-range and multi-select popups fit 768/390 widths')
  assert.deepEqual(errors, [])
  await writeFile(new URL('edge-cases-result.json', output), JSON.stringify({ passed: true, checks, errors }, null, 2))
  console.log(JSON.stringify({ passed: true, checks, errors }, null, 2))
} catch (error) {
  await shot('edge-case-failure')
  await writeFile(new URL('edge-cases-result.json', output), JSON.stringify({ passed: false, error: String(error), checks, errors }, null, 2))
  throw error
} finally {
  await browser.close()
}
