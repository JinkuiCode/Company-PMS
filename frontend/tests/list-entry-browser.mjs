import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { chromium, expect } from '@playwright/test'
const server = await createServer({ server: {host:'127.0.0.1',port:19263,strictPort:true}, cacheDir:'../.runtime/list-entry-cache', optimizeDeps:{entries:['tests/fixtures/list-entry.html']} })
let browser
try {
  await server.listen()
  browser = await chromium.launch({channel:'msedge',headless:true})
  const page = await browser.newPage({viewport:{width:1366,height:768}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.addInitScript(()=>localStorage.setItem('pms:query-workspace:v2:9901:entry-document',JSON.stringify([{version:2,name:'个人默认',isDefault:true,definitions:[{field:'code',shown:true,operator:'contains',value:'A-2025',valueEnd:null}],preferences:{}}])))
  await page.goto('http://127.0.0.1:19263/tests/fixtures/list-entry.html')
  const count=page.getByLabel('单据查询次数')
  await expect(count).toHaveText('0')
  await page.getByRole('button',{name:'完成依赖加载',exact:true}).click()
  await expect(page.getByRole('region',{name:'单据测试'}).getByRole('textbox',{name:'查询1值',exact:true})).toHaveValue('A-2025')
  await expect(count).toHaveText('0')
  await page.getByRole('button',{name:'完成数据加载',exact:true}).click()
  await expect(count).toHaveText('1')
  await expect(page.getByLabel('单据查询条件')).toContainText('A-2025')
  await expect(page.getByLabel('报表查询次数')).toHaveText('0')
  await expect(page.getByLabel('延迟字段查询次数')).toHaveText('0')
  await page.getByRole('button',{name:'加载字段目录',exact:true}).click()
  await expect(page.getByLabel('延迟字段查询次数')).toHaveText('1')
  await expect(page.getByLabel('枚举查询次数')).toHaveText('0')
  await page.getByRole('button',{name:'加载状态枚举',exact:true}).click()
  await expect(page.getByLabel('枚举查询次数')).toHaveText('1')
  await expect(page.getByLabel('引用查询次数')).toHaveText('0')
  await page.getByRole('button',{name:'刷新引用字段',exact:true}).click()
  await expect.poll(async()=>Number(await page.getByLabel('引用待处理数').innerText())).toBeGreaterThan(1)
  await page.getByRole('button',{name:'完成引用校验',exact:true}).click()
  await expect(page.getByLabel('引用查询次数')).toHaveText('1')
  await page.getByRole('region',{name:'单据测试'}).getByRole('button',{name:'重置',exact:true}).click()
  await expect(count).toHaveText('1')
  const required=page.getByRole('region',{name:'必输测试'})
  await expect(required.getByRole('button',{name:'查询',exact:true})).toBeDisabled()
  await expect(required.locator('.pms-condition-required')).toHaveText('*')
  assert.equal(await required.locator('.pms-condition-required').evaluate(e=>getComputedStyle(e).color), 'rgb(220, 38, 38)')
  await required.getByRole('button',{name:'方案设置',exact:true}).click()
  await expect(page.locator('.pms-query-settings-row .pms-condition-required')).toHaveCount(1)
  await expect(page.getByRole('region',{name:'报表测试'}).locator('.pms-condition-required')).toHaveCount(0)
  assert.deepEqual(errors,[])
  console.log('List entry browser passed: personal default once, readiness, report idle, red required star, reset manual')
} finally {await browser?.close();await server.close()}
