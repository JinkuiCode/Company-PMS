import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { chromium, expect } from '@playwright/test'
const server = await createServer({ server: { host: '127.0.0.1', port: 19261, strictPort: true }, cacheDir: '../.runtime/query-popup-test-cache', optimizeDeps: { entries: ['tests/fixtures/query-popup.html'] } })
let browser, page, release
const errors = []
try {
  await server.listen()
  const base = `http://127.0.0.1:${server.httpServer.address().port}`
  browser = await chromium.launch({ channel: 'msedge', headless: true })
  page = await browser.newPage({ viewport: { width: 1366, height: 768 } })
  page.setDefaultTimeout(10000)
  page.on('pageerror', e => errors.push(e.message))
  let delayed = false
  await page.route('**/__popup-candidates?*', async route => {
    if (delayed) await new Promise(resolve => { release = resolve })
    await route.fulfill({ json: { items: [{ value: 'A-202503', label: 'A-202503' }, { value: 'A-202638', label: 'A-202638' }], hasMore: false } })
  })
  await page.goto(`${base}/tests/fixtures/query-popup.html`)
  const panel = label => page.getByRole('dialog', { name: `${label}列筛选面板`, exact: true })
  const trigger = label => page.getByRole('button', { name: `${label}列筛选`, exact: true })
  const checkbox = (surface, name) => surface.locator('label').filter({ has: page.getByRole('checkbox', { name, exact: true }) })
  const select = (surface, name) => surface.locator('.pms-form-control').filter({ has: page.getByRole('combobox', { name, exact: true }) })
  await trigger('项目编码').click()
  await expect(panel('项目编码').getByText('A-202503', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '外部区域', exact: true }).click()
  await expect(panel('项目编码')).toHaveCount(0)
  await trigger('项目编码').click()
  await page.locator('.pms-column-header-label').filter({ hasText: /^项目编码$/ }).click()
  await expect(panel('项目编码')).toHaveCount(0)
  for (const label of ['项目编码', '物料名称', '产品线', '日期', '数量']) {
    await trigger(label).click()
    await expect(panel(label)).toBeVisible()
    await expect(page.locator('.pms-column-filter-panel')).toHaveCount(1)
  }
  await trigger('数量').click()
  await expect(page.locator('.pms-column-filter-panel')).toHaveCount(0)
  await trigger('项目编码').click()
  await checkbox(panel('项目编码'), 'A-202638').click()
  await panel('项目编码').getByRole('button', { name: '应用', exact: true }).click()
  await expect(page.getByLabel('已应用筛选')).toContainText('A-202503')
  await trigger('项目编码').click()
  await checkbox(panel('项目编码'), 'A-202638').click()
  await page.getByRole('button', { name: '外部区域', exact: true }).click()
  await expect(page.getByLabel('已应用筛选')).not.toContainText('A-202638')

  await trigger('产品线').click()
  await panel('产品线').getByRole('button', { name: '按条件', exact: true }).click()
  await select(panel('产品线'), '列筛选条件').click()
  await page.getByRole('option', { name: '属于', exact: true }).click()
  await expect(panel('产品线')).toBeVisible()
  await select(panel('产品线'), '列筛选值').click()
  await page.getByRole('option', { name: 'Single', exact: true }).click()
  await expect(panel('产品线')).toBeVisible()
  await page.keyboard.press('Escape')
  await select(panel('产品线'), '列筛选条件').click()
  await page.getByRole('option', { name: '引用', exact: true }).click()
  const nested = page.getByRole('dialog', { name: '引用产品线', exact: true })
  await checkbox(nested, '选择Single').click()
  await expect(panel('产品线')).toBeVisible()
  await nested.getByRole('button', { name: '确认引用', exact: true }).click()
  await expect(panel('产品线')).toBeVisible()
  await expect(panel('产品线').getByRole('button', { name: '列筛选引用值', exact: true })).toContainText('Single')
  await page.getByRole('button', { name: '外部区域', exact: true }).click()
  await trigger('项目编码').click()
  await panel('项目编码').getByRole('button', { name: '按条件', exact: true }).click()
  await select(panel('项目编码'), '列筛选条件').click()
  await page.getByRole('option', { name: '引用', exact: true }).click()
  const projectDialog = page.getByRole('dialog', { name: '引用项目档案', exact: true })
  await select(projectDialog, '引用产品线').click()
  await page.getByRole('option', { name: 'Single', exact: true }).click()
  await expect(projectDialog).toBeVisible()
  await expect(panel('项目编码')).toBeVisible()
  await projectDialog.getByRole('button', { name: '批量粘贴', exact: true }).click()
  await select(projectDialog, '批量匹配字段').click()
  await page.getByRole('option', { name: '名称', exact: true }).click()
  await expect(projectDialog).toBeVisible()
  await projectDialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(panel('项目编码')).toBeVisible()
  await page.getByRole('button', { name: '外部区域', exact: true }).click()
  await trigger('日期').click()
  await panel('日期').getByRole('button', { name: '按条件', exact: true }).click()
  await panel('日期').locator('.pms-condition-value .el-input__wrapper').click()
  await panel('日期').locator('.el-date-table td.available:not(.prev-month):not(.next-month)').first().click()
  await expect(panel('日期')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.pms-column-filter-panel')).toHaveCount(0)

  delayed = true
  const pending = page.waitForRequest('**/__popup-candidates?field=code')
  await trigger('项目编码').click()
  await pending
  await page.getByRole('button', { name: '外部区域', exact: true }).click()
  release?.(); delayed = false
  await expect(page.locator('.pms-column-filter-panel')).toHaveCount(0)
  await trigger('物料名称').click()
  await page.getByRole('button', { name: '切换表格', exact: true }).click()
  await expect(page.locator('.pms-column-filter-panel')).toHaveCount(0)
  await page.getByRole('button', { name: '切换表格', exact: true }).click()
  await trigger('物料名称').click()
  await expect(panel('物料名称')).toBeVisible()
  await page.getByRole('button', { name: '外部区域', exact: true }).click()

  await page.getByRole('button', { name: '查询引用值', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '引用产品线', exact: true })
  await expect(dialog.getByRole('columnheader', { name: '编码', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('textbox', { name: '搜索引用记录' })).toHaveAttribute('placeholder', '搜索产品线名称')
  await dialog.getByRole('textbox', { name: '搜索引用记录' }).fill('Bench')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await checkbox(dialog, '选择8吋Bench').click()
  await dialog.getByRole('textbox', { name: '搜索引用记录' }).fill('Single')
  await dialog.getByRole('button', { name: '查询', exact: true }).click()
  await checkbox(dialog, '选择Single').click()
  await expect(dialog.getByRole('table', { name: '已选记录列表' })).toContainText('8吋Bench')
  await expect(dialog).not.toContainText('499413')
  await dialog.getByRole('button', { name: '批量粘贴', exact: true }).click()
  await expect(dialog.getByRole('combobox', { name: '批量匹配字段' })).toHaveCount(0)
  await dialog.getByRole('textbox', { name: '批量查询数据' }).fill('8吋Bench\nSingle')
  await dialog.getByRole('button', { name: '批量查询', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('匹配 2 条')
  await dialog.getByRole('button', { name: '确认引用', exact: true }).click()
  await expect(page.getByLabel('已选值')).toHaveText('[499413,100002]')
  await expect(page.getByRole('button', { name: '查询引用值', exact: true })).toContainText('8吋Bench、Single')
  await page.route(`${base}/__popup-oa`, route => route.fulfill({ contentType: 'text/html; charset=utf-8', body: `<meta charset="UTF-8"><button style="position:fixed;bottom:0;right:0">OA外部区域</button><iframe title="PMS" src="${base}/tests/fixtures/query-popup.html" style="width:100%;height:650px;border:0"></iframe>` }))
  await page.goto(`${base}/__popup-oa`)
  const frame = page.frameLocator('iframe')
  await frame.getByRole('button', { name: '项目编码列筛选', exact: true }).click()
  await expect(frame.locator('.pms-column-filter-panel')).toHaveCount(1)
  await page.getByRole('button', { name: 'OA外部区域', exact: true }).click()
  await expect(frame.locator('.pms-column-filter-panel')).toHaveCount(0)
  assert.deepEqual(errors, [])
  console.log('PASS shared popup lifecycle and name-only product line reference')
} catch (error) {
  console.error('Popup regression:', errors, await page?.locator('body').innerText())
  await page?.screenshot({ path: '/private/tmp/pms-query-popup-failure.png' })
  throw error
} finally {
  release?.()
  await browser?.close()
  await server.close()
}
