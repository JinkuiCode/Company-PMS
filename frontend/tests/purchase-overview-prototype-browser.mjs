import { chromium } from 'playwright'
import { strict as assert } from 'node:assert'
import { projects, lines, summarize } from '../prototypes/purchase-overview/data.js'

const summaries = summarize(lines)
assert.equal(summaries.length, 12)
assert.equal(summaries.filter(p => p.code === 'A-202638').length, 2)
assert.equal(summaries[0].percent, 70)
assert.ok(summaries.every(p => p.total === p.counts.reduce((a, b) => a + b, 0)))
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = [], apiRequests = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', r => { if (r.url().includes('/api/')) apiRequests.push(r.url()) })
const url = 'http://127.0.0.1:5174/prototypes/purchase-overview.html'
async function ready(variant) {
  await page.goto(`${url}?variant=${variant}`)
  await page.locator('[data-project="project-0"]').waitFor()
  await page.evaluate(() => document.fonts.ready)
}
try {
  await ready('A')
  await page.screenshot({ path: '../.runtime/purchase-overview-A.png', fullPage: true })
  assert.equal(await page.locator('.side-menu').evaluate(e => e.getBoundingClientRect().width), 64)
  assert.ok(await page.locator('.keyword').evaluate(e => e.getBoundingClientRect().width >= 200))
  assert.ok(await page.getByRole('columnheader', { name: '行完成率', exact: true }).evaluate(e => e.getBoundingClientRect().right <= innerWidth))
  await page.locator('[data-project="project-0"] .text-action').click()
  await page.locator('.context-strip strong').waitFor()
  assert.equal(await page.locator('.detail-table tbody tr').count(), 40)
  assert.ok((await page.locator('.detail-table tbody').innerText()).includes('8吋Bench'))
  assert.ok(!(await page.locator('.detail-table tbody').innerText()).includes('Single'))
  await page.locator('.detail-table tbody tr').filter({ hasText: '已完成' }).first().getByRole('button', { name: '明细', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: '采购申请行明细 · 模拟批次' })
  await drawer.waitFor()
  assert.equal(await page.locator('.drawer-scroll').first().locator('tbody tr').count(), 2)
  assert.equal(await page.locator('.drawer-scroll').nth(1).locator('tbody tr').count(), 4)
  await drawer.locator('.el-drawer__close-btn').click()
  await page.getByRole('button', { name: '返回总进度' }).click()
  await page.locator('[data-project="project-1"] .text-action').click()
  assert.equal(await page.locator('.detail-table tbody tr').count(), 16)
  await page.getByRole('button', { name: '采购明细', exact: true }).click()
  assert.equal(await page.locator('.detail-table tbody tr').count(), 50)
  await page.getByRole('button', { name: '项目总进度', exact: true }).click()
  await page.getByRole('combobox', { name: '每页条数' }).selectOption('10')
  await page.getByRole('button', { name: '下一页' }).click()
  await page.locator('.summary-table .text-action').first().click()
  await page.getByRole('button', { name: '返回总进度' }).click()
  assert.match(await page.locator('.page-controls').innerText(), /2 \/ 2/)
  await page.getByRole('button', { name: '重置', exact: true }).click()
  assert.match(await page.locator('.empty-state').innerText(), /设置条件后/)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  assert.equal(await page.locator('.summary-table tbody tr').count(), 10)
  await page.getByRole('textbox', { name: '关键词', exact: true }).fill('不存在的项目')
  assert.equal(await page.locator('.summary-table tbody tr').count(), 10)
  await page.getByRole('button', { name: '查询', exact: true }).click()
  assert.equal(await page.locator('.summary-table tbody tr').count(), 0)
  await ready('B')
  await page.locator('[data-project="project-0"]').click()
  assert.equal(await page.locator('.linked-panel').count(), 0)
  await page.locator('[data-project="project-0"] .text-action').click()
  assert.equal(await page.locator('.linked-panel tbody tr').count(), 40)
  await page.locator('[data-project="project-1"]').click()
  assert.equal(await page.locator('.linked-panel tbody tr').count(), 16)
  await page.screenshot({ path: '../.runtime/purchase-overview-B.png', fullPage: true })
  await ready('C')
  await page.locator('[data-project="project-0"] .text-action').click()
  await page.locator('[data-project="project-1"] .text-action').click()
  assert.equal(await page.locator('.expanded-row').count(), 2)
  await page.screenshot({ path: '../.runtime/purchase-overview-C.png', fullPage: true })
  await page.locator('.expanded-title .text-action').first().click()
  await page.getByRole('button', { name: '返回总进度' }).click()
  assert.equal(await page.locator('.expanded-row').count(), 2)
  for (const width of [1920, 1182, 390]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 900 })
    await ready('A')
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
    assert.equal(overflow, false, `page overflow at ${width}`)
    await page.screenshot({ path: `../.runtime/purchase-overview-${width}.png`, fullPage: true })
  }
  assert.deepEqual(errors, [])
  assert.deepEqual(apiRequests, [])
  console.log(`PASS: three prototypes, ${lines.length} fixture lines, scoped drilldown, return page, split linkage, multi-expand, batch detail, manual query, responsive layouts, no API calls`)
} finally {
  await browser.close()
}
