import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
const output = new URL('../../outputs/theme-controls/', import.meta.url)
await mkdir(output, {recursive:true})
const browser=await chromium.launch({channel:'msedge',headless:true})
const context=await browser.newContext({viewport:{width:1440,height:900}})
const page=await context.newPage()
page.setDefaultTimeout(9000)
const errors=[], forbidden=[], checks=[]
page.on('pageerror',error=>errors.push(error.message))
page.on('request',request=>{const u=new URL(request.url());if(u.protocol.startsWith('http') && (u.origin!=='http://127.0.0.1:5184'||u.pathname.startsWith('/api')))forbidden.push(request.url())})
const shot=async name=>page.screenshot({path:new URL(name+'.png',output).pathname,fullPage:true,animations:'disabled'})
const visiblePop=()=>page.locator('.el-select__popper:visible')
const select=name=>page.locator('.pms-form-control').filter({has:page.getByRole('combobox',{name,exact:true})})
const chooseTheme=async name=>{await page.getByRole('button',{name:'切换外观'}).click();await page.getByRole('menuitem',{name:new RegExp(name)}).click()}
const formTab=()=>page.getByRole('button',{name:'表单与状态',exact:true}).click()
const queryTab=()=>page.getByRole('button',{name:'查询与引用',exact:true}).click()
const panel=name=>page.getByRole('dialog',{name:`${name}列筛选面板`,exact:true})
try {
  for(const [id,label,color] of [['blue','办公蓝','rgb(37, 99, 235)'],['teal','青绿','rgb(15, 118, 110)'],['graphite','石墨','rgb(39, 39, 42)']]) {
    await page.goto(`http://127.0.0.1:5184/?theme=${id}`)
    await page.evaluate(()=>document.fonts.ready)
    await expect(page.getByRole('grid')).toBeVisible()
    await select('样稿字段名').first().click()
    await expect(page.getByRole('option',{name:'客户名称',exact:true})).toBeVisible()
    assert.equal(await page.getByRole('option',{name:'项目编码',exact:true}).evaluate(e=>getComputedStyle(e).color),color)
    await shot(id+'-dropdown')
    await page.keyboard.press('Escape')
    await expect(visiblePop()).toHaveCount(0)
    await select('样稿条件').first().click()
    await expect(page.getByRole('option',{name:'不包含',exact:true})).toBeVisible()
    await page.getByRole('option',{name:'等于',exact:true}).click()
    await page.locator('[data-field=code]').getByRole('textbox').fill('DEMO-202601')
    await page.getByRole('button',{name:'查询',exact:true}).click()
    await expect(page.locator('.list-footer')).toContainText('共 1 条')
    await page.getByRole('button',{name:'重置',exact:true}).click()
    await expect(page.locator('.list-footer')).toContainText('共 24 条')

    await formTab()
    await expect(page.locator('.pms-form-control[aria-label="空选项"]')).not.toContainText('false')
    await expect(page.locator('.pms-form-control[aria-label="加载选择"]')).not.toContainText('false')
    await page.getByRole('textbox',{name:'项目名称输入',exact:true}).fill('保留输入-'+id)
    await select('档案类别').click()
    await expect(page.getByRole('option',{name:'历史分类（已停用）',exact:true})).toHaveAttribute('aria-disabled','true')
    await page.getByRole('option',{name:'备件',exact:true}).click()
    await select('产品线多选').click()
    await page.getByRole('option',{name:'Single',exact:true}).click()
    await expect(page.getByRole('option',{name:'Single',exact:true})).toHaveAttribute('aria-selected','true')
    await shot(id+'-multiselect')
    await page.keyboard.press('Escape')
    await select('部门树多选').click()
    await expect(page.getByRole('tree')).toBeVisible()
    await shot(id+'-tree')
    await page.keyboard.press('Escape')
    await page.locator('#preview-date').click()
    await expect(page.locator('.el-picker-panel:visible')).toBeVisible()
    await shot(id+'-date')
    await page.locator('.el-picker-panel:visible .el-date-table td.available:not(.prev-month):not(.next-month)').first().click()
    await expect(page.locator('#preview-date')).not.toHaveValue('2026-10-19')
    await page.locator('.pms-form-control[aria-label="日期范围"]').click()
    await expect(page.locator('.el-date-range-picker:visible')).toBeVisible()
    await shot(id+'-range')
    await page.keyboard.press('Escape')
    await page.getByRole('textbox',{name:'校验错误',exact:true}).fill('已补齐')
    await page.getByRole('button',{name:'校验样稿',exact:true}).click()
    await expect(page.getByRole('status')).toContainText('样稿校验通过')
    await expect(page.getByRole('status')).toHaveCSS('color','rgb(8, 126, 101)')
    await expect(page.getByRole('textbox',{name:'禁用输入',exact:true})).toBeDisabled()
    await expect(page.getByRole('textbox',{name:'只读文本',exact:true})).toHaveAttribute('readonly','')
    await page.getByRole('textbox',{name:'项目名称输入',exact:true}).focus()
    await expect.poll(()=>page.getByRole('textbox',{name:'项目名称输入',exact:true}).evaluate(e=>getComputedStyle(e.closest('.pms-form-control')).borderTopColor)).toBe(color)
    await shot(id+'-states')
    await chooseTheme(id==='blue'?'青绿':'办公蓝')
    await expect(page.getByRole('textbox',{name:'项目名称输入',exact:true})).toHaveValue('保留输入-'+id)
    await chooseTheme(label)
    await page.getByRole('button',{name:'打开抽屉',exact:true}).click()
    await select('抽屉档案类别').click()
    await expect(page.getByRole('option',{name:'主机',exact:true})).toBeVisible()
    await shot(id+'-drawer')
    await page.keyboard.press('Escape')
    await page.getByRole('button',{name:'取消',exact:true}).click()
    await expect(page.locator('.pms-form-drawer:visible')).toHaveCount(0)
    checks.push(id+': dropdown, operator/query, multi-select, tree, calendar/range, focus, disabled/readonly, validation, drawer, draft preservation')
    console.log(id+' controls passed')
  }
  await queryTab()
  await page.getByRole('button',{name:'样稿引用值',exact:true}).click()
  const reference=page.getByRole('dialog',{name:'引用产品线',exact:true})
  await expect(reference.getByRole('columnheader',{name:'编码',exact:true})).toHaveCount(0)
  await reference.locator('label').filter({has:page.getByRole('checkbox',{name:'选择8吋Bench',exact:true})}).click()
  await reference.getByRole('textbox',{name:'搜索引用记录',exact:true}).fill('Single')
  await reference.getByRole('button',{name:'查询',exact:true}).click()
  await reference.locator('label').filter({has:page.getByRole('checkbox',{name:'选择Single',exact:true})}).click()
  await expect(reference.getByRole('region',{name:'已选明细'})).toContainText('8吋Bench')
  await expect(reference.getByRole('region',{name:'已选明细'})).toContainText('Single')
  const heights=await reference.locator('.reference-toolbar > .pms-form-control, .reference-toolbar > .el-button').evaluateAll(es=>es.map(e=>Math.round(e.getBoundingClientRect().height)))
  assert.equal(new Set(heights).size,1,`reference row controls differ: ${heights}`)
  await shot('reference-selected')
  await reference.getByRole('button',{name:'确认引用',exact:true}).click()
  await expect(reference).not.toBeVisible()
  await expect(page.getByRole('button',{name:'样稿引用值',exact:true})).toContainText('2 条')
  await page.locator('.query-actions').getByRole('button',{name:'重置',exact:true}).click()

  await page.getByRole('button',{name:'项目编码列筛选',exact:true}).click()
  await expect(panel('项目编码')).toBeVisible()
  await page.getByRole('button',{name:'项目名称列筛选',exact:true}).click()
  await expect(page.locator('.pms-column-filter-panel')).toHaveCount(1)
  await expect(panel('项目名称')).toBeVisible()
  await shot('column-filter')
  await page.locator('.pms-header h1').click()
  await expect(page.locator('.pms-column-filter-panel')).toHaveCount(0)
  await page.getByRole('button',{name:'项目编码列筛选',exact:true}).click()
  await panel('项目编码').locator('label').filter({has:page.getByRole('checkbox',{name:'全选已加载值'})}).click()
  await panel('项目编码').locator('label').filter({has:page.getByRole('checkbox',{name:/DEMO-202601/})}).click()
  await panel('项目编码').getByRole('button',{name:'应用',exact:true}).click()
  await expect(page.locator('.list-footer')).toContainText('本页显示 1 条')
  await page.getByRole('button',{name:'重置',exact:true}).click()
  checks.push('reference preserves selection across searches, names only, equal heights; column popup single instance/outside close/local filtering')

  await page.getByRole('button',{name:'表格编辑',exact:true}).click()
  const cell=page.locator('.ag-center-cols-container .ag-row[row-id="1"] [col-id="name"]')
  await cell.dblclick()
  await page.getByRole('textbox',{name:'编辑项目名称',exact:true}).fill('表格编辑验证')
  await page.keyboard.press('Enter')
  await expect(cell).toContainText('表格编辑验证')
  await chooseTheme('青绿')
  await expect(cell).toContainText('表格编辑验证')
  await page.locator('.ag-center-cols-container .ag-row[row-id="1"] [col-id="product_line_id"]').dblclick()
  await select('编辑产品线').click()
  await shot('grid-select-editor')
  await page.getByRole('option',{name:'HSPM',exact:true}).click()
  await page.locator('.pms-header h1').click()
  await expect(page.locator('.ag-center-cols-container .ag-row[row-id="1"] [col-id="product_line_id"]')).toContainText('HSPM')
  checks.push('real AG Grid text/select editing and theme-switch preservation')
  for(const width of [1920,1366,768,390]){
    await page.setViewportSize({width,height:width<500?844:900})
    await queryTab()
    await shot('layout-'+width)
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`outer overflow at ${width}`)
    await formTab()
    await shot('form-'+width)
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`form outer overflow at ${width}`)
    const spills=await page.locator('.state-grid .pms-form-control').evaluateAll(es=>es.filter(e=>e.getBoundingClientRect().right>e.closest('.state-surface').getBoundingClientRect().right+1).length)
    assert.equal(spills,0,`control spills at ${width}`)
  }
  checks.push('1920/1366/768/390 responsive layout: no page or form control overflow')
  assert.deepEqual(errors,[])
  assert.deepEqual(forbidden,[])
  await writeFile(new URL('browser-result.json',output),JSON.stringify({passed:true,checks,errors,forbiddenRequests:forbidden,browser:await browser.version(),platform:process.platform},null,2))
  console.log(JSON.stringify({passed:true,checks,errors,forbiddenRequests:forbidden},null,2))
}catch(error){await shot('failure');await writeFile(new URL('browser-result.json',output),JSON.stringify({passed:false,error:String(error),checks,errors,forbiddenRequests:forbidden},null,2));throw error}
finally{await browser.close()}
