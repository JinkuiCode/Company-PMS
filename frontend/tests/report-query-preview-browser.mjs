import {chromium, expect} from '@playwright/test'
import assert from 'node:assert/strict'
const browser = await chromium.launch({channel:'msedge',headless:true})
const page = await browser.newPage({viewport:{width:1600,height:900}})
const errors=[], requests=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('request',r=>{if(r.url().includes('/api/')) requests.push(r.url())})
try {
  await page.goto('http://127.0.0.1:5191/prototypes/report-query-v2.html')
  await expect(page.getByRole('button',{name:'查询',exact:true})).toBeVisible()
  await page.evaluate(()=>document.fonts.ready)
  for (const report of ['即时库存查询','采购进度查询','物料收发明细']) {
    await page.getByRole('button',{name:report,exact:true}).click()
    const query=page.getByRole('button',{name:'查询',exact:true})
    if(report==='物料收发明细') {
      await expect(query).toBeDisabled()
      await page.getByRole('textbox',{name:'物料',exact:true}).fill('PFA')
      await expect(query).toBeDisabled()
      await page.locator('.pms-form-control').filter({has:page.getByRole('combobox',{name:'库存组织',exact:true})}).click()
      await page.getByRole('option',{name:'8吋半导体',exact:true}).click()
      await page.locator('.preview-header strong').click()
    }
    await expect(query).toBeEnabled()
    await query.click()
    await expect(page.locator('.el-message')).toHaveCount(0,{timeout:10000})
    await page.locator('.preview-header strong').click()
    await expect(page.locator('.preview-table tbody tr')).toHaveCount(30)
    const heights = await page.locator('.pms-report-query-surface').evaluate(el=>[...el.querySelectorAll('.pms-form-control,.el-button')].filter(e=>e.getBoundingClientRect().height).map(e=>e.getBoundingClientRect().height))
    assert.ok(heights.every(h=>Math.abs(h-32)<1),JSON.stringify(heights))
    await page.getByRole('button',{name:'添加条件',exact:true}).click()
    await page.locator('.pms-report-conditions').getByRole('button',{name:'添加条件',exact:true}).click()
    await page.getByRole('button',{name:'应用条件',exact:true}).click()
    await expect(page.getByRole('alert').filter({hasText:'请填写'})).toBeVisible()
    await page.getByRole('textbox',{name:'条件1值',exact:true}).fill('PFA')
    await page.getByRole('button',{name:'应用条件',exact:true}).click()
    await expect(page.locator('.preview-applied')).toContainText('PFA')
    await page.getByRole('button',{name:'保存查询方案',exact:true}).click()
    await page.getByRole('textbox',{name:'方案名称',exact:true}).fill('样稿验收')
    await page.getByRole('button',{name:'保存',exact:true}).click()
    await page.getByRole('button',{name:'重置',exact:true}).click()
    await expect(page.locator('.preview-table tbody tr')).toHaveCount(0)
    await page.locator('.pms-report-plans .el-select__wrapper').click()
    await page.getByRole('option',{name:'样稿验收',exact:true}).click()
    await expect(page.locator('.preview-applied')).toContainText('PFA')
    await expect(page.locator('.preview-table tbody tr')).toHaveCount(0)
    await query.click()
    await expect(page.locator('.el-message')).toHaveCount(0,{timeout:10000})
    await page.locator('.preview-header strong').click()
    await page.waitForTimeout(350)
    for (const width of [1366,1600]) {
      await page.setViewportSize({width,height:900})
      await page.screenshot({path:`../.runtime/query-v2-${report}-${width}.png`})
      const table=await page.locator('.preview-table').boundingBox()
      assert.ok(table.height>580)
      assert.equal(await page.locator('th[title]').count(),0)
    }
  }
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'../.runtime/query-v2-390.png'})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  assert.deepEqual(errors,[])
  assert.deepEqual(requests,[])
  console.log('Preview: equal 32px controls, three reports, conditions, plans, required inputs and no business requests passed.')
} finally {await browser.close()}
