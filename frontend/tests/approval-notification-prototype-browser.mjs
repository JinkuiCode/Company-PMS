import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const base = process.env.PMS_NOTICE_PROTOTYPE_URL || 'http://127.0.0.1:5197'
const browser = await chromium.launch({ channel: 'msedge', headless: true })
await mkdir('../.runtime/p20-notifications/screenshots', { recursive: true })
try {
  const page = await browser.newPage({ viewport: { width: 1366, height: 900 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route('**/*', route => new URL(route.request().url()).origin === base && !new URL(route.request().url()).pathname.startsWith('/api/') ? route.continue() : route.abort())
  await page.goto(`${base}/prototypes/approval-notifications/index.html`)
  await expect(page.getByRole('heading', { name: '审批通知 · 交互样稿' })).toBeVisible()
  await page.getByRole('button', { name: '打开通知' }).click()
  const dialog = page.getByRole('dialog', { name: '通知', exact: true })
  await expect(dialog.getByRole('tab', { name: '业务消息' })).toBeVisible()
  await expect(dialog.getByRole('tab', { name: '升级通知' })).toBeVisible()
  await dialog.getByRole('button', { name: /P2026-018/ }).click()
  await expect(dialog).toContainText('等待你审批')
  await dialog.getByRole('button', { name: '标为已读', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '已读', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '查看申请', exact: true }).click()
  const request = page.getByRole('dialog', { name: '档案变更申请' })
  await expect(request).toContainText('拟变更内容')
  await request.getByRole('button', { name: '关闭此对话框' }).click()
  for (const [code, state] of [['P2026-012','已通过'],['P2026-009','已退回'],['P2026-003','已撤回']]) {
    await dialog.getByRole('button', { name: new RegExp(code) }).click()
    await expect(dialog.getByTestId('notice-detail')).toContainText(state)
  }
  await dialog.getByRole('button', { name: /P2026-018/ }).focus()
  await page.keyboard.press('Enter')
  await expect(dialog.getByTestId('notice-detail')).toContainText('等待你审批')
  await page.screenshot({ path: '../.runtime/p20-notifications/screenshots/prototype-initial.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  for (const state of ['加载','空列表','读取失败','无权访问']) {
    await page.getByLabel('预览状态').selectOption({ label: state })
    await page.getByRole('button', { name: '打开通知' }).click()
    await expect(dialog).toContainText({ '加载':'正在读取通知','空列表':'暂无业务消息','读取失败':'读取失败，请重试','无权访问':'当前无权查看业务消息' }[state])
    await expect(dialog.getByText('精密装配线', { exact: true })).toHaveCount(0)
    await page.keyboard.press('Escape')
  }
  await page.getByLabel('预览状态').selectOption('normal')
  await page.getByLabel('预览投递管理权限').check()
  await page.getByRole('button', { name: '打开通知' }).click()
  await dialog.getByText('邮件投递', { exact: true }).click()
  await expect(dialog).toContainText('投递结果未知')
  await dialog.getByRole('button', { name: '受控重试' }).click()
  const retry = page.getByRole('dialog', { name: '确认重试邮件' })
  await expect(retry.getByRole('button', { name: '确认重试', exact: true })).toBeDisabled()
  await retry.getByRole('textbox', { name: '重试原因', exact: true }).fill('已通过模拟收件箱核查')
  await retry.getByText('已人工核查，确认用户未收到邮件', { exact: true }).click()
  await expect(retry.getByRole('checkbox', { name: '已人工核查，确认用户未收到邮件' })).toBeChecked()
  await retry.getByRole('button', { name: '确认重试', exact: true }).click()
  await expect(dialog).toContainText('待投递')
  await dialog.getByRole('button', { name: '查看申请', exact: true }).click()
  await request.getByRole('button', { name: '退回', exact: true }).click()
  await expect(request).toContainText('退回时请填写意见')
  await request.getByRole('button', { name: '关闭此对话框' }).click()
  await page.keyboard.press('Escape')
  await page.getByLabel('预览投递管理权限').uncheck()
  for (const theme of ['blue','teal','graphite']) {
    await page.getByLabel('预览主题').selectOption(theme)
    await page.getByRole('button', { name: '打开通知' }).click()
    await expect(dialog.getByRole('button', { name: '刷新' })).toBeVisible()
    await page.screenshot({ path: `../.runtime/p20-notifications/screenshots/prototype-${theme}.png`, animations: 'disabled' })
    await page.keyboard.press('Escape')
  }
  await page.setViewportSize({ width: 518, height: 760 })
  await page.getByRole('button', { name: '打开通知' }).click()
  await expect(dialog).toBeVisible()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.screenshot({ path: '../.runtime/p20-notifications/screenshots/prototype-narrow.png', animations: 'disabled' })
  assert.deepEqual(errors, [])
  console.log('PASS: isolated prototype states, keyboard, explicit read, request entry, themes and narrow layout')
} finally { await browser.close() }
