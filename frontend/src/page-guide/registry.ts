export function findGuideEntries(guide: PageGuide, section: GuideSection, query = ''): GuideEntry[] {
  const needle = query.trim().toLowerCase()
  return guide[section].filter(item => !needle || `${item.label} ${item.logic} ${item.group}`.toLowerCase().includes(needle))
}
